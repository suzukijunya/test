export function questionById(id: string): Question | undefined {
  return QUESTIONS.find((q) => q.id === id);
}

/** 日付から決まる「今日の質問」（ふたりとも同じ質問になる） */
export function dailyQuestion(dateStr: string): Question {
  let h = 0;
  for (const c of dateStr) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return QUESTIONS[h % QUESTIONS.length];
}

/** まだ出していない質問からランダムに選ぶ */
export function randomQuestion(usedIds: string[], category?: Category, rand = Math.random): Question {
  const pool = QUESTIONS.filter((q) => (!category || q.category === category) && !usedIds.includes(q.id));
  const from = pool.length ? pool : QUESTIONS.filter((q) => !category || q.category === category);
  return from[Math.floor(rand() * from.length)];
}

/** ゆるく一致判定（選択肢は完全一致、自由回答は空白・記号を除いて比較） */
export function looselyEqual(a: string, b: string): boolean {
  const n = (s: string) => s.normalize('NFKC').toLowerCase().replace(/[\s、。,.!！?？〜~ー・]/g, '');
  return !!a && !!b && n(a) === n(b);
}
